import { lex, parse } from './sqlparse';

/* =====================================================================================
 * Release pack: collects the scripts of one module (tables, ALTERs, data, procedures) into one
 * ordered deployment file, makes procedures re-runnable and warns about risky statements.
 * ===================================================================================== */

export type ItemKind = 'table' | 'alter' | 'data' | 'proc' | 'other';

export const KIND_ORDER: Record<ItemKind, number> = { table: 0, alter: 1, data: 2, proc: 3, other: 4 };
export const KIND_NAME: Record<ItemKind, string> = { table: 'Table', alter: 'Table change', data: 'Data', proc: 'Procedure / view / function', other: 'Other' };

export interface ReleaseItem {
  id: string;
  name: string;
  kind: ItemKind;
  sql: string;
}

export interface PrepOptions {
  createOrAlter: boolean; // CREATE PROCEDURE -> CREATE OR ALTER PROCEDURE
  stripUse: boolean; // remove USE [UatDatabase] lines
  stripBanner: boolean; // remove SSMS "Object: ... Script Date: ..." comment
}

const OBJECTS = new Set(['PROC', 'PROCEDURE', 'FUNCTION', 'VIEW', 'TRIGGER']);

/** Cleans a script that was generated by SSMS so it can be run on another server. */
export function prepareScript(sql: string, o: PrepOptions): string {
  let s = sql;
  if (o.stripBanner) s = s.replace(/^[ \t]*\/\*+\s*Object:[^\r\n]*?Script Date:[^\r\n]*?\*+\/[ \t]*(\r?\n)?/gim, '');
  if (o.stripUse) {
    s = s.replace(/^[ \t]*USE[ \t]+(\[[^\]\r\n]+\]|[\w$#@]+)[ \t]*;?[ \t]*(\r?\n)?/gim, '');
    s = s.replace(/^(\s*\/\*[\s\S]*?\*\/)?\s*GO[ \t]*(\r?\n|$)/i, '$1\n');
  }
  if (o.createOrAlter) {
    const code = lex(s).toks;
    for (let i = code.length - 2; i >= 0; i--) {
      const t = code[i];
      const lineStart = i === 0 || /[\r\n]/.test(s.slice(code[i - 1].to, t.from));
      if (t.up === 'CREATE' && lineStart && OBJECTS.has(code[i + 1].up)) s = s.slice(0, t.to) + ' OR ALTER' + s.slice(t.to);
    }
  }
  return s;
}

export interface Finding {
  level: 'warn' | 'info';
  text: string;
}

/** Looks for things that usually should not reach production. */
export function lintScript(sql: string): Finding[] {
  const out: Finding[] = [];
  const { code, units } = parse(sql);
  const add = (level: Finding['level'], text: string) => out.push({ level, text });

  const uses = new Set<string>();
  const uat = new Set<string>();
  let dropCount = 0;
  let identityOn = 0;
  let identityOff = 0;
  let createTable = 0;
  let guards = 0;

  for (const u of units) {
    const toks = code.slice(u.t0, u.t1 + 1);
    const first = toks[0]?.up;
    const ups = toks.map((t) => t.up);
    const snip = sql.slice(toks[0].from, toks[Math.min(3, toks.length - 1)].to).replace(/\s+/g, ' ');
    if (first === 'USE') uses.add(toks[1]?.text ?? '');
    if (first === 'DROP' || first === 'TRUNCATE') {
      dropCount++;
      add('warn', `${snip} ... will remove data or objects.`);
    }
    if ((first === 'DELETE' || first === 'UPDATE') && !ups.includes('WHERE') && !ups.includes('MERGE')) {
      add('warn', `${first} without WHERE: ${snip} ...`);
    }
    if (first === 'SET' && ups[1] === 'IDENTITY_INSERT') (ups[3] === 'ON' ? identityOn++ : identityOff++);
    if (first === 'CREATE' && ups[1] === 'TABLE') createTable++;
  }
  for (const t of code) {
    if (t.kind === 'id' && /(^|[^a-z])uat\d*([^a-z]|$)/i.test(t.text)) uat.add(t.text);
    if (t.up === 'OBJECT_ID' || t.up === 'EXISTS') guards++;
  }

  if (uses.size) add('warn', `Contains USE ${[...uses].join(', ')}. Remove it unless production uses the same database name.`);
  if (uat.size) add('warn', `Names that look like UAT: ${[...uat].slice(0, 6).join(', ')}.`);
  if (identityOn !== identityOff) add('warn', 'SET IDENTITY_INSERT ON / OFF are not balanced.');
  if (createTable && !guards && !dropCount) add('info', 'CREATE TABLE has no existence check, so the script fails if it runs twice. Turn on "Re-runnable" when cleaning tables.');
  if (/\bINSERT\b/i.test(sql) && !/\b(NOT EXISTS|MERGE|IDENTITY_INSERT)\b/i.test(sql)) add('info', 'Plain INSERTs will create duplicates if the script runs twice. Use "Insert only missing rows" or MERGE.');
  return out;
}

export interface ReleaseOptions {
  title: string;
  database: string; // adds USE [db] when set
  go: boolean; // GO after each item
}

const pad = (n: number) => String(n).padStart(2, '0');

export function buildRelease(items: ReleaseItem[], o: ReleaseOptions): string {
  const d = new Date();
  const stamp = `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;
  const lines: string[] = [`/* ${o.title || 'Release'}  |  ${stamp}  |  ${items.length} item(s)`];
  items.forEach((it, i) => lines.push(`   ${i + 1}. [${KIND_NAME[it.kind]}] ${it.name}`));
  lines.push('*/', '');
  if (o.database.trim()) lines.push(`USE ${/^\[.*\]$/.test(o.database.trim()) ? o.database.trim() : `[${o.database.trim()}]`}`, 'GO', '');
  lines.push('SET NOCOUNT ON;', 'GO', '');

  items.forEach((it, i) => {
    const body = it.sql.replace(/\s+$/, '');
    lines.push(`/* ---- ${i + 1}. ${it.name} (${KIND_NAME[it.kind]}) ---- */`, body);
    if (o.go && !/\bGO\s*$/i.test(body)) lines.push('GO');
    lines.push('');
  });
  return lines.join('\r\n');
}
